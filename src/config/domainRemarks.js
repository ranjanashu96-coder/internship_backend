/**
 * Lookup remarks for a given domain.
 * Exact match → partial match → loose word match → default fallback.
 */
export const getDomainRemarks = (domainName) => {
  if (!domainName) return getDefaultRemarks();

  const normalized = String(domainName)
    .trim()
    .toLowerCase()
    .replace(/\s+/g, " ");

  // 1) Exact match
  if (DOMAIN_REMARKS[normalized]) {
    return DOMAIN_REMARKS[normalized];
  }

  // 2) Partial match (one contains other)
  const partial = Object.keys(DOMAIN_REMARKS).find(
    (k) => k.includes(normalized) || normalized.includes(k),
  );

  if (partial) return DOMAIN_REMARKS[partial];

  // 3) Loose word match — any significant word present
  const words = normalized
    .split(/\s+/)
    .filter((w) => w.length > 3);

  if (words.length > 0) {
    let bestKey = null;
    let bestScore = 0;

    for (const key of Object.keys(DOMAIN_REMARKS)) {
      let score = 0;
      for (const word of words) {
        if (key.includes(word)) score += 1;
      }
      if (score > bestScore) {
        bestScore = score;
        bestKey = key;
      }
    }

    if (bestKey && bestScore > 0) {
      return DOMAIN_REMARKS[bestKey];
    }
  }

  return getDefaultRemarks();
};

